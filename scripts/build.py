class TagChecker(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.stack: list[str] = []
        self.errors: list[str] = []

    def handle_starttag(self, tag: str, attrs) -> None:
        if tag not in VOID_TAGS:
            self.stack.append(tag)

    def handle_endtag(self, tag: str) -> None:
        if tag in VOID_TAGS:
            return
        if not self.stack or self.stack[-1] != tag:
            self.errors.append(tag)
            return
        self.stack.pop()


def local_target(url: str) -> str | None:
    path = url.split("#", 1)[0]
    if path.startswith(ORIGIN):
        path = path[len(ORIGIN):]
    prefix = f"{BASE}/" if BASE else "/"
    if path != prefix and not path.startswith(prefix):
        return None
    relative = path[len(BASE):].lstrip("/") if BASE else path.lstrip("/")
    if relative == "":
        return "index.html"
    if relative.endswith("/"):
        return relative + "index.html"
    return relative


def verify(pages: dict[str, str], sitemap: str, robots: str) -> None:
    problems: list[str] = []
    public_locs = []
    for relative, page in pages.items():
        if not page.startswith(GENERATED):
            problems.append(f"{relative} is missing the generator comment")
        if page.count("<h1>") != 1:
            problems.append(f"{relative} should have one h1")
        if "Stranger Thoughts" not in page:
            problems.append(f"{relative} dropped the brand")
        lowered = page.lower()
        for banned in (
            "lorem ipsum", "your-slug-here", "yyyy-mm-dd", "replace this title",
            "paypal", "stripe", "venmo", "buy now", "add to cart", "donate now",
            "googletagmanager", "google-analytics", "gtag(",
            "plausible.io",
        ):
            if banned in lowered:
                problems.append(f"{relative} contains {banned}")
        if re.search(r"\$\s*\d", page):
            problems.append(f"{relative} contains a dollar amount")
        if SOCIAL_RE.search(page) or "twitter.com/" in lowered or "x.com/" in lowered:
            problems.append(f"{relative} links a social profile")
        if STREET_RE.search(page) or POBOX_RE.search(page):
            problems.append(f"{relative} contains a street address")
        if SITE["domain_status"] != "live" and SITE["planned_domain"] in lowered:
            problems.append(f"{relative} mentions the planned domain before it is live")
        if "not an AI" not in page or "waitlist only" not in lowered:
            problems.append(f"{relative} is missing the honesty note or waitlist line")
        if "Mailing address coming soon" not in page:
            problems.append(f"{relative} is missing the mailing-address placeholder")
        if REFERRER_META not in page:
            problems.append(f"{relative} is missing the referrer policy")
        if CSP_META not in page:
            problems.append(f"{relative} is missing the Content-Security-Policy")
        if "script-src 'none'" not in page or "form-action mailto:" not in page:
            problems.append(f"{relative} CSP must set script-src 'none' and form-action mailto:")
        if CLASSIC_SCRIPT_RE.search(page):
            problems.append(f"{relative} has a non-JSON-LD script")
        if "javascript:" in lowered or "addeventlistener" in lowered:
            problems.append(f"{relative} contains classic JavaScript")
        if 'href="http://' in page or "href='http://" in page or 'src="http://' in page:
            problems.append(f"{relative} has an http:// link")
        for blob in re.findall(
            r'<script type="application/ld\+json">\n(.*?)\n</script>', page, re.S
        ):
            if "http://" in blob:
                problems.append(f"{relative} JSON-LD contains an http:// URL")
        for tag in ANCHOR_RE.findall(page):
            href_match = re.search(r'href="([^"]*)"', tag)
            if not href_match:
                continue
            outbound = href_match.group(1)
            if not outbound.startswith("https://") or outbound.startswith(ORIGIN + "/"):
                continue
            rel_match = re.search(r'rel="([^"]*)"', tag)
            rel_parts = rel_match.group(1).split() if rel_match else []
            if "noopener" not in rel_parts or "noreferrer" not in rel_parts:
                problems.append(
                    f"{relative} outbound https link is missing rel=\"noopener noreferrer\": {outbound}"
                )
        forms = page.count("<form")
        if relative == "waitlist/index.html":
            if forms != 1 or 'action="mailto:' not in page:
                problems.append("waitlist form must be a single mailto form")
        elif forms:
            problems.append(f"{relative} has an unexpected form")
        checker = TagChecker()
        checker.feed(page)
        if checker.errors or checker.stack:
            problems.append(f"{relative} has unbalanced HTML tags {checker.errors} stack={checker.stack}")
        for match in HREF_RE.finditer(page):
            url = match.group(1)
            if url.startswith("#"):
                if url != "#content":
                    problems.append(f"{relative} has an unknown anchor {url}")
                continue
            if url.startswith("mailto:"):
                if not url.startswith("mailto:" + SITE["waitlist_email"]):
                    problems.append(f"{relative} mailto is not the waitlist address")
                continue
            if url.startswith("http://"):
                problems.append(f"{relative} has an http:// link: {url}")
                continue
            if url.startswith("https://") and not url.startswith(ORIGIN + "/"):
                in_anchor = any(
                    f'href="{url}"' in tag for tag in ANCHOR_RE.findall(page)
                )
                if not in_anchor:
                    problems.append(f"{relative} loads an external URL outside a link: {url}")
                continue
            target = local_target(url)
            if target is None:
                problems.append(f"{relative} has a link outside the site: {url}")
                continue
            static = target in {"css/styles.css", "favicon.svg"}
            if not static and target not in pages:
                problems.append(f"{relative} links missing {target}")
        if relative != "404.html":
            canonical = absolute(href_file(relative if relative != "index.html" else ""))
            if relative == "index.html":
                canonical = absolute(href())
            elif relative.endswith("/index.html"):
                canonical = absolute(href(relative[: -len("index.html")]))
            public_locs.append(canonical)
            if canonical not in sitemap:
                problems.append(f"sitemap is missing {canonical}")
        elif "404.html" in sitemap or "noindex" not in page:
            problems.append("404 page should be noindex and absent from the sitemap")
    if "Sitemap:" not in robots or absolute(href_file("sitemap.xml")) not in robots:
        problems.append("robots.txt is missing the sitemap URL")
    ignore = (ROOT / ".gitignore").read_text(encoding="utf-8").splitlines()
    for line in (".env", ".env.*", "!.env.example", "*.pem", "*.key"):
        if line not in ignore:
            problems.append(f".gitignore is missing {line}")
    policy = ROOT / "SECURITY.md"
    advisory = "https://github.com/dmlehinger-web/stranger-thoughts/security/advisories/new"
    if not policy.exists() or advisory not in policy.read_text(encoding="utf-8"):
        problems.append("SECURITY.md must point at GitHub private vulnerability reporting")
    if problems:
        for problem in problems:
            print(f"build error: {problem}", file=sys.stderr)
        raise SystemExit(1)


def write_text(path: Path, content: str) -> None:
    if not content.endswith("\n"):
        content += "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def clean_stale_posts(slugs: set[str]) -> None:
    folder = ROOT / "thoughts"
    if not folder.exists():
        return
    for child in folder.iterdir():
        if not child.is_dir() or child.name in slugs:
            continue
        files = [item for item in child.rglob("*") if item.is_file()]
        expected = child / "index.html"
        if files and files != [expected]:
            die(f"thoughts/{child.name} is stale and holds unexpected files")
        if expected.exists():
            expected.unlink()
        child.rmdir()


def sitemap_xml(entries: list[tuple[str, str]]) -> str:
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ]
    for loc, lastmod in entries:
        lines.extend([
            "  <url>",
            f"    <loc>{esc(loc)}</loc>",
            f"    <lastmod>{lastmod}</lastmod>",
            "  </url>",
        ])
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


