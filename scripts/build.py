def die(message: str) -> None:
    print(f"build error: {message}", file=sys.stderr)
    raise SystemExit(1)


def load_json(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        die(f"{path.relative_to(ROOT)} is not valid JSON: {exc}")
    if not isinstance(data, dict):
        die(f"{path.relative_to(ROOT)} must be a JSON object")
    return data


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def parse_date(value: str, label: str):
    if not isinstance(value, str):
        die(f"{label} must be a YYYY-MM-DD string")
    try:
        return datetime.strptime(value, "%Y-%m-%d").date()
    except ValueError:
        die(f"{label} must be a real YYYY-MM-DD date")


def human_date(iso: str) -> str:
    year, month, day = iso.split("-")
    return f"{MONTHS[int(month) - 1]} {int(day)}, {year}"


def require(obj: dict, keys: list[str], label: str) -> None:
    missing = [key for key in keys if key not in obj or obj[key] in ("", None, [], {})]
    if missing:
        die(f"{label} is missing {', '.join(missing)}")


def walk_strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from walk_strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from walk_strings(item)


def text_block(value, label: str, minimum: int, maximum: int) -> str:
    if not isinstance(value, str):
        die(f"{label} must be a string")
    cleaned = value.strip()
    if len(cleaned) < minimum or len(cleaned) > maximum:
        die(f"{label} must be {minimum}-{maximum} characters")
    if "@@" in cleaned:
        die(f"{label} may not contain @@")
    return cleaned


def string_list(value, label: str, minimum: int) -> list[str]:
    if not isinstance(value, list) or not value:
        die(f"{label} must be a non-empty list of strings")
    cleaned = []
    for index, item in enumerate(value, start=1):
        cleaned.append(text_block(item, f"{label} item {index}", minimum, 1600))
    return cleaned


