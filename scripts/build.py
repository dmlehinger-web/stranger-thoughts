def href(*parts: str) -> str:
    cleaned = [part.strip("/") for part in parts if part and part.strip("/")]
    if not cleaned:
        return f"{BASE}/" if BASE else "/"
    tail = "/".join(cleaned)
    return f"{BASE}/{tail}/" if BASE else f"/{tail}/"


def href_file(path: str) -> str:
    relative = path.lstrip("/")
    return f"{BASE}/{relative}" if BASE else f"/{relative}"


def absolute(path: str) -> str:
    return ORIGIN + path


def guard_tree(value, label: str) -> None:
    for item in walk_strings(value):
        if STREET_RE.search(item) or POBOX_RE.search(item):
            die(f"{label} contains a street or post-office address")
        if PHONE_RE.search(item):
            die(f"{label} contains a phone number")
        if SOCIAL_RE.search(item) or HANDLE_RE.search(item):
            die(f"{label} links a social account or handle")
        if "http://" in item:
            die(f"{label} contains an http:// URL; remote links must use https://")
        if "javascript:" in item.lower():
            die(f"{label} contains a javascript: URL")
        if "@@" in item:
            die(f"{label} contains a template token")


for label, document in (
    ("data/site.json", SITE),
    ("data/home.json", HOME),
    ("data/how.json", HOW),
    ("data/about.json", ABOUT),
    ("data/waitlist.json", WAITLIST),
    ("data/thoughts.json", THOUGHTS),
):
    guard_tree(document, label)


def load_posts() -> list[dict]:
    folder = DATA / "posts"
    posts = []
    seen = set()
    for path in sorted(folder.glob("*.json")):
        if path.name.startswith("_"):
            continue
        post = load_json(path)
        label = f"data/posts/{path.name}"
        require(post, ["slug", "title", "date", "kicker", "description", "blocks"], label)
        guard_tree(post, label)
        slug = post["slug"]
        if slug != path.stem or not SLUG_RE.fullmatch(slug):
            die(f"{label} slug must match the filename")
        if slug == "your-slug-here":
            die(f"{label} still has the template slug")
        if slug in seen:
            die(f"duplicate slug {slug}")
        seen.add(slug)
        post["slug"] = slug
        post["title"] = text_block(post["title"], f"{label} title", 8, 90)
        post["kicker"] = text_block(post["kicker"], f"{label} kicker", 2, 40)
        post["description"] = text_block(post["description"], f"{label} description", 40, 170)
        post["date"] = post["date"]
        dated = parse_date(post["date"], label)
        if dated > CHECKED:
            die(f"{label} is dated after data/site.json checked")
        if not isinstance(post["blocks"], list) or len(post["blocks"]) < 2:
            die(f"{label} needs at least two blocks")
        paragraphs = 0
        for index, block in enumerate(post["blocks"], start=1):
            if not isinstance(block, dict) or set(block) != {"type", "text"}:
                die(f"{label} block {index} must have type and text")
            kind = block["type"]
            if kind not in {"p", "h2"}:
                die(f"{label} block {index} type must be p or h2")
            minimum = 60 if kind == "p" else 8
            block["text"] = text_block(block["text"], f"{label} block {index}", minimum, 1500)
            if kind == "p":
                paragraphs += 1
        if paragraphs < 2:
            die(f"{label} needs at least two paragraphs")
        posts.append(post)
    if not posts:
        die("data/posts has no publishable notes")
    posts.sort(key=lambda item: (item["date"], item["slug"]), reverse=True)
    titles = [item["title"] for item in posts]
    if len(titles) != len(set(titles)):
        die("two posts share a title")
    return posts


POSTS = load_posts()


def paragraphs(items: list[str]) -> str:
    return "\n".join(f"<p>{esc(item)}</p>" for item in items)


def item_list(items: list[str]) -> str:
    lis = "\n".join(f"  <li>{esc(item)}</li>" for item in items)
    return f'<ul class="plain-list">\n{lis}\n</ul>'


def status_band() -> str:
    return f'<p class="status">{esc(SITE["status"])}</p>'


def crumbs(items: list[tuple[str, str | None]]) -> str:
    rendered = []
    for label, path in items:
        if path is None:
            rendered.append(f'<li aria-current="page">{esc(label)}</li>')
        else:
            rendered.append(f'<li><a href="{esc(href(path))}">{esc(label)}</a></li>')
    inside = "".join(rendered)
    return f'<nav class="crumbs" aria-label="Breadcrumb"><ol>{inside}</ol></nav>'


def actions(primary: str = "Join the waitlist") -> str:
    return (
        '<p class="actions">'
        f'<a class="button" href="{esc(href("waitlist"))}">{esc(primary)}</a>'
        f' <a class="button button-quiet" href="{esc(href("thoughts"))}">Read the thoughts</a>'
        "</p>"
    )


def address_box() -> str:
    return (
        '<div class="address">'
        '<p class="kicker">Where to send paper</p>'
        f"<p>{esc(SITE['mailing_address'])}</p>"
        "</div>"
    )


def render_sections(sections, label: str) -> str:
    if not isinstance(sections, list) or not sections:
        die(f"{label} sections must be a non-empty list")
    parts = []
    for index, section in enumerate(sections, start=1):
        section_label = f"{label} section {index}"
        if not isinstance(section, dict):
            die(f"{section_label} must be an object")
        extra = set(section) - SECTION_KEYS
        if extra or "title" not in section:
            die(f"{section_label} has unexpected or missing fields")
        if not any(key in section for key in ("paragraphs", "items", "closing")):
            die(f"{section_label} needs paragraphs, items, or closing")
        bits = ["<section>"]
        if "kicker" in section:
            bits.append(f'<p class="kicker">{esc(text_block(section["kicker"], section_label + " kicker", 2, 24))}</p>')
        bits.append(f"<h2>{esc(text_block(section['title'], section_label + ' title', 3, 80))}</h2>")
        if "paragraphs" in section:
            bits.append(paragraphs(string_list(section["paragraphs"], section_label + " paragraphs", 40)))
        if "items" in section:
            bits.append(item_list(string_list(section["items"], section_label + " items", 12)))
        if section.get("show_address") is True:
            bits.append(address_box())
        elif "show_address" in section:
            die(f"{section_label} show_address must be true; the words come from site.json")
        if "closing" in section:
            bits.append(paragraphs(string_list(section["closing"], section_label + " closing", 20)))
        bits.append("</section>")
        parts.append("\n".join(bits))
    return "\n".join(parts)


def thought_list(posts: list[dict], heading: str) -> str:
    items = []
    for post in posts:
        url = href("thoughts", post["slug"])
        items.append(
            "<li>"
            f'<p class="meta"><time datetime="{esc(post["date"])}">{esc(human_date(post["date"]))}</time>'
            f' · <span class="kicker">{esc(post["kicker"])}</span></p>'
            f'<{heading}><a href="{esc(url)}">{esc(post["title"])}</a></{heading}>'
            f"<p>{esc(post['description'])}</p>"
            "</li>"
        )
    return '<ol class="thought-list">\n' + "\n".join(items) + "\n</ol>"


def nav_html(section: str) -> str:
    parts = []
    for label, path, key in NAV:
        current = ' aria-current="page"' if key == section else ""
        parts.append(f'<li><a href="{esc(href(path))}"{current}>{esc(label)}</a></li>')
    return "\n".join(parts)


def footer_links() -> str:
    return "\n".join(
        f'<li><a href="{esc(href(path))}">{esc(label)}</a></li>'
        for label, path, _key in NAV
    )


def jsonld(graph: list[dict]) -> str:
    payload = {"@context": "https://schema.org", "@graph": graph}
    raw = json.dumps(payload, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    return f'<script type="application/ld+json">\n{raw}\n</script>'


def website_node() -> dict:
    return {
        "@type": "WebSite",
        "name": SITE["name"],
        "url": absolute(href()),
        "description": HOME["description"],
        "inLanguage": "en-US",
    }


def page_node(title: str, description: str, path: str, kind: str = "WebPage") -> dict:
    return {
        "@type": kind,
        "name": title,
        "description": description,
        "url": absolute(href(path)),
        "isPartOf": {"@type": "WebSite", "name": SITE["name"], "url": absolute(href())},
        "inLanguage": "en-US",
    }


def fill(template: str, mapping: dict[str, str], label: str) -> str:
    page = template
    for token, value in mapping.items():
        if token not in page:
            die(f"{label} is missing {token}")
        page = page.replace(token, value)
    leftover = TOKEN_RE.search(page)
    if leftover:
        die(f"{label} left {leftover.group(0)} unreplaced")
    return page


def render(title: str, description: str, path: str, body: str, section: str,
           graph: list[dict], robots: str = "", og_type: str = "website",
           extra_head: str = "") -> str:
    if path == "404":
        canonical = absolute(href_file("404.html"))
    else:
        canonical = absolute(href(path))
    robot_tag = f'<meta name="robots" content="{esc(robots)}">' if robots else ""
    document_title = title if title == SITE["name"] else f"{title} · {SITE['name']}"
    mapping = {
        "@@TITLE@@": esc(document_title),
        "@@DESCRIPTION@@": esc(description),
        "@@CANONICAL@@": esc(canonical),
        "@@OG_TYPE@@": esc(og_type),
        "@@SITE_NAME@@": esc(SITE["name"]),
        "@@EXTRA_HEAD@@": extra_head,
        "@@ROBOTS@@": robot_tag,
        "@@FAVICON@@": esc(href_file("favicon.svg")),
        "@@CSS@@": esc(href_file("css/styles.css")),
        "@@JSONLD@@": jsonld(graph),
        "@@HOME@@": esc(href()),
        "@@NAV@@": nav_html(section),
        "@@FOOTER@@": esc(SITE["footer"]),
        "@@ADDRESS_LINE@@": esc(SITE["mailing_address"]),
        "@@FOOTER_LINKS@@": footer_links(),
        "@@BODY@@": body,
    }
    return GENERATED + fill(TEMPLATE, mapping, "templates/page.html")


def render_blocks(blocks: list[dict]) -> str:
    parts = []
    for block in blocks:
        if block["type"] == "h2":
            parts.append(f"<h2>{esc(block['text'])}</h2>")
        else:
            parts.append(f"<p>{esc(block['text'])}</p>")
    return "\n".join(parts)


def adjacent(post: dict | None, label: str) -> str:
    if post is None:
        return ""
    url = href("thoughts", post["slug"])
    return f'<a href="{esc(url)}"><span>{esc(label)}</span> {esc(post["title"])}</a>'


def render_home() -> str:
    require(HOME, ["title", "description", "kicker", "headline", "lede", "steps_heading", "steps", "steps_note", "thoughts_heading", "thoughts_intro"], "data/home.json")
    text_block(HOME["description"], "home description", 40, 170)
    steps = HOME["steps"]
    if not isinstance(steps, list) or not 3 <= len(steps) <= 4:
        die("home needs three or four steps")
    step_html = []
    for index, step in enumerate(steps, start=1):
        if not isinstance(step, dict) or set(step) != {"title", "text"}:
            die(f"home step {index} must have title and text")
        title = text_block(step["title"], f"home step {index} title", 3, 40)
        text = text_block(step["text"], f"home step {index} text", 40, 500)
        step_html.append(f"<li><h3>{esc(title)}</h3><p>{esc(text)}</p></li>")
    body = "\n".join([
        '<article class="sheet">',
        f'<p class="kicker">{esc(text_block(HOME["kicker"], "home kicker", 3, 60))}</p>',
        f'<h1>{esc(text_block(HOME["headline"], "home headline", 8, 90))}</h1>',
        f'<p class="lede">{esc(text_block(HOME["lede"], "home lede", 80, 700))}</p>',
        status_band(),
        actions(),
        f'<h2>{esc(text_block(HOME["steps_heading"], "home steps heading", 3, 40))}</h2>',
        '<ol class="steps">',
        "\n".join(step_html),
        "</ol>",
        f'<p>{esc(text_block(HOME["steps_note"], "home steps note", 20, 300))}</p>',
        f'<p><a href="{esc(href("how-it-works"))}">Read how it works</a></p>',
        f'<h2>{esc(text_block(HOME["thoughts_heading"], "home thoughts heading", 3, 40))}</h2>',
        f'<p>{esc(text_block(HOME["thoughts_intro"], "home thoughts intro", 20, 300))}</p>',
        thought_list(POSTS[:RECENT_LIMIT], "h3"),
        f'<p><a href="{esc(href("thoughts"))}">All thoughts</a></p>',
        "</article>",
    ])
    description = HOME["description"]
    graph = [website_node(), page_node(HOME["title"], description, "")]
    return render(HOME["title"], description, "", body, "home", graph)


def render_simple_page(document: dict, path: str, section: str, label: str, kind: str = "WebPage") -> str:
    require(document, ["title", "description", "intro", "sections"], label)
    description = text_block(document["description"], f"{label} description", 40, 170)
    title = text_block(document["title"], f"{label} title", 3, 80)
    body = "\n".join([
        '<article class="sheet">',
        crumbs([("Home", ""), (title, None)]),
        f"<h1>{esc(title)}</h1>",
        status_band(),
        paragraphs(string_list(document["intro"], f"{label} intro", 40)),
        render_sections(document["sections"], label),
        actions(),
        "</article>",
    ])
    graph = [page_node(title, description, path, kind)]
    return render(title, description, path, body, section, graph)


def render_waitlist() -> str:
    label = "data/waitlist.json"
    require(WAITLIST, ["title", "description", "intro", "form_heading", "form_note", "subject", "submit", "fields", "after"], label)
    description = text_block(WAITLIST["description"], "waitlist description", 40, 170)
    title = text_block(WAITLIST["title"], "waitlist title", 3, 40)
    subject = text_block(WAITLIST["subject"], "waitlist subject", 3, 80)
    email = SITE["waitlist_email"]
    mailto_url = f"mailto:{email}?subject={quote(subject)}"
    warning = ""
    if SITE["waitlist_email_is_placeholder"]:
        warning = (
            '<p class="help">This is a placeholder address. Mail sent to it will not '
            "be delivered until a real mailbox is connected.</p>"
        )
    fields = WAITLIST["fields"]
    if not isinstance(fields, list) or len(fields) != 3:
        die("waitlist needs name, email, and piece fields")
    rendered_fields = []
    seen = set()
    for index, field in enumerate(fields, start=1):
        field_label = f"waitlist field {index}"
        if not isinstance(field, dict):
            die(f"{field_label} must be an object")
        require(field, ["name", "label", "type", "required", "maxlength"], field_label)
        name = field["name"]
        if name not in FIELD_NAMES or name in seen:
            die("waitlist fields must be name, email, and piece, once each")
